# -*- coding: utf-8 -*-
"""Pillow port of CoverUp's creative/render.py compositor, for running outside Picard.

Same layout as CoverUp's compose(): the band logo (or the artist name as text) in a band 22% of
the height at the top/centre/bottom, the album title and year in a line near the bottom, white or
near-black text chosen from the background, with a soft shadow. Text and logos are drawn here,
never by the AI model, so they are sharp and spelled right.

Fonts: a font file (.ttf/.otf) placed in the artist's folder is used for that artist (drop the
band's own font there); otherwise --title-font; otherwise DejaVu Sans.
"""
from __future__ import annotations

import hashlib
import io
import random
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

GENERATED_MARK = "Generated by CoverUp"
FONT_EXTS = (".ttf", ".otf", ".ttc")
_DEFAULT_FONTS = {
    True: ["DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
           "LiberationSans-Bold.ttf", "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"],
    False: ["DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
            "LiberationSans-Regular.ttf", "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"],
}


def is_generated(data: bytes | None) -> bool:
    """Art this batch generated carries the mark in its JPEG comment (kept in files and tags)."""
    return bool(data) and GENERATED_MARK.encode() in data[:8192]


def artist_font(artist_dir: Path | None) -> str | None:
    """A font file the user put in the artist folder (the band's own lettering), if any."""
    if not artist_dir:
        return None
    try:
        fonts = sorted(p for p in Path(artist_dir).iterdir() if p.is_file() and p.suffix.lower() in FONT_EXTS)
    except OSError:
        return None
    return str(fonts[0]) if fonts else None


# Fonts for generated covers: free Open Font License families (Google Fonts, via Fontsource),
# chosen per library from what strong covers in each genre use: restrained serif or minimal
# sans for ambient (ECM-style), blackletter/gothic for metal, classic book serifs for classical.
FONTS_DIR = Path(__file__).resolve().parent / "coverup_fonts"
GENRE_FONTS = {
    "ambient_music": ["cormorant-garamond", "josefin-sans", "tenor-sans", "raleway", "space-grotesk", "montserrat"],
    "extreme_music": ["grenze-gotisch", "pirata-one", "new-rocker", "unifrakturcook", "metal-mania", "oswald"],
    "classical_music": ["cormorant-garamond", "eb-garamond", "playfair-display", "cinzel", "libre-baskerville"],
    "": ["bebas-neue", "oswald", "archivo-black", "playfair-display", "montserrat", "space-grotesk"],
}
KEEP_CASE = {"unifrakturcook", "unifrakturmaguntia", "pirata-one", "grenze-gotisch"}   # blackletter in capitals is unreadable


def _covers(path, text):
    try:
        from fontTools.ttLib import TTFont
        cmap = TTFont(path, lazy=True).getBestCmap()
    except Exception:
        return True                                # cannot check: assume it can
    return all(ord(ch) in cmap for ch in text if not ch.isspace())


def choose_fonts(library, artist, texts, fonts_dir=None, override=None):
    """(display_font, text_font, keep_case, family). One family per artist (same look on all of a
    band's generated covers), from the library's genre set, skipping fonts that lack a letter used."""
    if override:
        return override, override, False, Path(override).stem
    d = Path(fonts_dir or FONTS_DIR)
    pool = GENRE_FONTS.get(library, GENRE_FONTS[""])
    start = int(hashlib.md5(str(artist or "").casefold().encode()).hexdigest()[:6], 16) % len(pool)
    for fam in pool[start:] + pool[:start]:
        disp, text = d / f"{fam}-display.ttf", d / f"{fam}-text.ttf"
        if disp.exists() and text.exists() and all(_covers(str(p), s) for p in (disp, text) for s in texts):
            return str(disp), str(text), fam in KEEP_CASE, fam
    return None, None, False, "DejaVu Sans"


def logo_transparent(logo: Image.Image) -> Image.Image:
    """Logos without transparency (some Wikidata files) get their plain background removed."""
    lg = logo.convert("RGBA")
    if logo.mode in ("RGBA", "LA") or "transparency" in logo.info:
        if lg.getchannel("A").getextrema()[0] < 250:
            return lg
    w, h = lg.size
    corners = [lg.getpixel(p)[:3] for p in ((0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1))]
    bg = corners[0]
    if any(max(abs(a - b) for a, b in zip(c, bg)) > 24 for c in corners):
        return lg                                  # no plain background to remove
    px = lg.load()
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            d = max(abs(r - bg[0]), abs(g - bg[1]), abs(b - bg[2]))
            if d <= 24:
                px[x, y] = (r, g, b, 0)
            elif d <= 60:
                px[x, y] = (r, g, b, int(a * (d - 24) / 36))
    return lg


def _font(path: str | None, px: int, bold: bool):
    for cand in ([path] if path else []) + _DEFAULT_FONTS[bold]:
        try:
            return ImageFont.truetype(cand, max(8, int(px)))
        except OSError:
            continue
    return ImageFont.load_default(max(8, int(px)))


def _fit_font(draw, text, path, max_width, start_px, bold=True):
    px = start_px
    while px > 8:
        f = _font(path, px, bold)
        if draw.textlength(text, font=f) <= max_width:
            return f
        px *= 0.9
    return _font(path, 8, bold)


def _auto_text_color(img: Image.Image, box) -> tuple:
    """White on dark backgrounds, near-black on light ones (CoverUp: lightness < 140)."""
    x0, y0, x1, y1 = [int(v) for v in box]
    region = img.crop((max(0, x0), max(0, y0), min(img.width, x1), min(img.height, y1))).convert("RGB")
    small = region.resize((24, max(1, int(24 * region.height / max(1, region.width)))))
    px = list(small.getdata())
    light = sum((max(p) + min(p)) / 2 for p in px) / max(1, len(px))      # HSL lightness, as Qt
    return (255, 255, 255) if light < 140 else (17, 17, 17)


def _draw_text(img, text, font, box, color):
    x0, y0, x1, y1 = box
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    bbox = d.textbbox((0, 0), text, font=font)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    x = x0 + (x1 - x0 - tw) / 2 - bbox[0]
    y = y0 + (y1 - y0 - th) / 2 - bbox[1]
    shadow = (0, 0, 0, 170) if sum(color) / 3 > 100 else (255, 255, 255, 150)
    off = max(1.0, font.size / 18)
    d.text((x + off, y + off), text, font=font, fill=shadow)
    layer = layer.filter(ImageFilter.GaussianBlur(off / 2))
    ImageDraw.Draw(layer).text((x, y), text, font=font, fill=color + (255,))
    img.alpha_composite(layer)


def compose(background: Image.Image, artist="", album="", year=None, logo: Image.Image | None = None,
            show_logo=True, show_title=True, position="top", font_path: str | None = None,
            text_font: str | None = None, keep_case: bool = False) -> Image.Image:
    size = min(background.width, background.height)
    left, top_ = (background.width - size) // 2, (background.height - size) // 2
    img = background.crop((left, top_, left + size, top_ + size)).convert("RGBA")
    if not (show_logo or show_title):
        return img
    s = float(size)
    margin = s * 0.06
    band_h = s * 0.22
    top = {"top": margin, "center": s / 2 - band_h / 2, "bottom": s - margin - band_h - s * 0.1}.get(position, margin)
    color = _auto_text_color(img, (0, top, s, top + band_h))
    draw = ImageDraw.Draw(img)
    if show_logo:
        if logo is not None:
            lg = logo_transparent(logo)
            lg.thumbnail((int(s - 2 * margin), int(band_h)), Image.LANCZOS)
            if lg.width < s - 2 * margin and lg.height < band_h:               # small logos grow to fit
                k = min((s - 2 * margin) / lg.width, band_h / lg.height)
                lg = lg.resize((max(1, int(lg.width * k)), max(1, int(lg.height * k))), Image.LANCZOS)
            x = int(margin + (s - 2 * margin - lg.width) / 2)
            y = int(top + (band_h - lg.height) / 2)
            img.alpha_composite(lg, (x, y))
        elif artist:
            name = artist if keep_case else artist.upper()
            f = _fit_font(draw, name, font_path, s - 2 * margin, s * 0.11, bold=True)
            _draw_text(img, name, f, (margin, top, s - margin, top + band_h), color)
    if show_title and album:
        title = album + (f"  ·  {year}" if year else "")
        f = _fit_font(draw, title, text_font or font_path, s - 2 * margin, s * 0.055, bold=False)
        ty = s - margin - s * 0.08 if position != "bottom" else top + band_h
        tcolor = _auto_text_color(img, (margin, ty, s - margin, ty + s * 0.08))   # its own background
        _draw_text(img, title, f, (margin, ty, s - margin, ty + s * 0.08), tcolor)
    return img


def procedural(style: str, size: int, seed: int, palette: list[str]) -> Image.Image:
    """Offline background (CoverUp's 'gradient' style with vignette and grain; other styles fall back
    to it here). Only used when no AI service is available and templates are allowed."""
    rnd = random.Random(seed)
    cols = []
    for c in palette or []:
        try:
            cols.append(Image.new("RGB", (1, 1), c).getpixel((0, 0)))
        except ValueError:
            pass
    cols = cols or [(34, 34, 34), (136, 136, 136), (221, 221, 221), (192, 57, 43)]
    img = Image.new("RGB", (size, size))
    tilt = rnd.uniform(0.4, 1.0)
    px = img.load()
    for y in range(size):
        for x in range(0, size, 4):
            t = min(1.0, max(0.0, (x * tilt + y) / (size * (1 + tilt))))
            pos = t * (len(cols) - 1)
            i = min(int(pos), len(cols) - 2) if len(cols) > 1 else 0
            f = pos - i
            a, b = cols[i], cols[min(i + 1, len(cols) - 1)]
            c = tuple(int(a[k] + (b[k] - a[k]) * f) for k in range(3))
            for dx in range(4):
                if x + dx < size:
                    px[x + dx, y] = c
    vign = Image.radial_gradient("L").resize((size, size))
    img = Image.composite(Image.new("RGB", (size, size), (0, 0, 0)), img, vign.point(lambda v: int(max(0, v - 150) * 1.3)))
    return img


def encode_generated(img: Image.Image, method: str, template: str, quality=93) -> bytes:
    """JPEG with the 'Generated by CoverUp' mark in its comment, so later runs can tell it apart."""
    rgb = img.convert("RGB")
    buf = io.BytesIO()
    rgb.save(buf, "JPEG", quality=quality, optimize=True,
             comment=f"{GENERATED_MARK} ({'AI' if method == 'ai' else 'template'}; style: {template})".encode())
    return buf.getvalue()
