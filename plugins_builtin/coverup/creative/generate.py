"""Produce generated artwork candidates (tier G) by AI or by the offline template renderer, then
composite the band logo and album title. Every result carries its provenance."""

from __future__ import annotations

import logging
import random
import time
from dataclasses import dataclass

from .. import imaging
from ..model import ArtType, Candidate, Query, Tier
from ..net import HttpClient
from . import ai
from .render import compose, disc_mask, procedural
from .template_engine import CUSTOM, Template, build_prompt, custom_template, load_templates

log = logging.getLogger("coverup.creative")

GENERATED_PREFIX = "Generated by CoverUp"


class ConsentRequired(Exception):
    """A remote AI service would receive album details and the user has not agreed yet."""

    def __init__(self, host: str):
        super().__init__(f"Consent needed to send album details to {host}")
        self.host = host


@dataclass
class CreativeOptions:
    method: str  # ai | template
    template: Template
    count: int = 4
    art_type: ArtType = ArtType.FRONT
    show_logo: bool = True
    show_title: bool = True
    position: str = "top"
    logo_data: bytes | None = None
    reference: bytes | None = None  # low-res cover for image-to-image (AI only)
    seed: int | None = None


def resolve_template(settings, extra_dirs=()) -> Template:
    name = settings["creative_template"]
    if name == CUSTOM:
        return custom_template(settings["creative_custom_prompt"])
    templates = load_templates(*extra_dirs)
    return templates.get(name) or templates.get("art") or next(iter(templates.values()))


def comment_for(method: str, template: str) -> str:
    return f"{GENERATED_PREFIX} ({'AI' if method == 'ai' else 'template'}; style: {template})"


def generate(settings, http: HttpClient, q: Query, opts: CreativeOptions) -> list[Candidate]:
    """Return up to ``opts.count`` generated candidates. Raises ConsentRequired for an un-approved remote AI."""
    seed0 = opts.seed if opts.seed is not None else random.randint(1, 2**31 - 1)
    size = int(settings["ai_size"] or 1024)
    logo_img = imaging.load(opts.logo_data) if opts.logo_data else None
    prompt = build_prompt(opts.template, q, bool(settings["creative_match_era"]), bool(settings["creative_match_genre"]))
    backgrounds: list[tuple[bytes | None, int, str]] = []  # (raw bytes or None for procedural, seed, model)
    method = opts.method

    if method == "ai":
        backend = ai.make_backend(settings["ai_backend"], http, settings)
        if backend is None:
            log.warning("AI generation requested but no AI backend is configured; using the offline template")
            method = "template"
        else:
            if ai.is_remote(backend.url) and ai.host_of(backend.url) not in (settings["ai_consented_hosts"] or []):
                raise ConsentRequired(ai.host_of(backend.url))
            ref = opts.reference
            if ref and ai.is_remote(backend.url) and not settings["ai_allow_remote_reference"]:
                log.info("Not sending the reference image to a remote AI service (not enabled)")
                ref = None
            if ref and not backend.supports_img2img():
                ref = None
            started = time.monotonic()
            req = ai.GenRequest(prompt, opts.template.negative, size, seed0, max(1, opts.count), ref)
            log.info("AI generation: backend=%s model=%s seed=%s n=%d img2img=%s prompt=%r", backend.NAME, backend.model or "-", seed0, req.n, bool(ref), prompt)
            images = backend.generate(req)
            log.info("AI generation returned %d image(s) in %.1fs", len(images), time.monotonic() - started)
            backgrounds = [(data, seed0 + i, backend.model or backend.NAME) for i, data in enumerate(images[: opts.count])]
            if not backgrounds:
                log.warning("AI backend returned no images; using the offline template")
                method = "template"
    if method == "template":
        backgrounds = [(None, seed0 + i, "procedural") for i in range(max(1, opts.count))]

    out: list[Candidate] = []
    for i, (raw, seed, model) in enumerate(backgrounds):
        if raw is None:
            bg = procedural(opts.template.procedural, size, seed, opts.template.palette)
        else:
            bg = imaging.load(raw)
            if bg.isNull():
                continue
        art = compose(
            bg, q.artist, q.album, q.year, logo_img,
            show_logo=opts.show_logo and opts.template.overlay_logo, show_title=opts.show_title and opts.template.overlay_title,
            position=opts.position,
        ) if opts.art_type == ArtType.FRONT else bg
        if opts.art_type == ArtType.DISC:
            art = disc_mask(art)
        data = imaging.encode(art, "png" if opts.art_type == ArtType.DISC else "jpeg", 93)
        c = Candidate(
            provider="generated", provider_id=f"gen-{seed}-{i}", url="", art_type=opts.art_type, tier=Tier.G,
            width=art.width(), height=art.height(), dims_known=True, bytes=len(data), thumb_data=data, data=data,
            generated=True, comment=comment_for(method, opts.template.name), attribution="CoverUp",
        )
        c.extra.update({
            "method": method, "template": opts.template.name, "seed": seed, "model": model,
            "prompt": prompt if method == "ai" else "", "backend": settings["ai_backend"] if method == "ai" else "procedural",
            "logo": bool(logo_img is not None and not logo_img.isNull()),
        })
        out.append(c)
    log.info("Generated %d %s candidate(s) with template %s", len(out), opts.art_type.value, opts.template.name)
    return out
