"""Core data model. Pure Python: no Picard or Qt imports."""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum


class ArtType(str, Enum):
    FRONT = "front"
    BACK = "back"
    DISC = "disc"
    BOOKLET = "booklet"
    ARTIST_THUMB = "artist-thumb"
    ARTIST_BACKGROUND = "artist-background"
    ARTIST_LOGO = "artist-logo"
    ARTIST_BANNER = "artist-banner"
    OTHER = "other"


class Tier(str, Enum):
    """How strongly a candidate is tied to the exact release."""

    A = "A"  # exact release (CAA release image, matched Discogs release, local art for this release)
    B = "B"  # release group (CAA release group, Fanart.tv, TheAudioDB)
    C = "C"  # unanchored web/other source: only visual consensus can vouch for it
    G = "G"  # generated by CoverUp (AI / template); never outranks real art by default

    @property
    def rank(self) -> int:
        return {"A": 3, "B": 2, "C": 1, "G": 0}[self.value]


@dataclass
class Query:
    artist: str = ""
    album: str = ""
    year: int | None = None
    barcode: str = ""
    catalog_number: str = ""
    label: str = ""
    country: str = ""
    format: str = ""
    medium_count: int = 1
    release_mbid: str = ""
    rg_mbid: str = ""
    artist_mbid: str = ""
    discogs_release_id: int | None = None
    genre: str = ""
    comment: str = ""  # MusicBrainz release disambiguation, e.g. "2009 remaster"
    track_count: int = 0
    album_dirs: list[str] = field(default_factory=list)  # folders currently holding the album's files

    @property
    def label_text(self) -> str:
        return f"{self.artist} - {self.album}" + (f" ({self.year})" if self.year else "")


@dataclass
class Candidate:
    provider: str
    provider_id: str
    url: str
    art_type: ArtType = ArtType.FRONT
    tier: Tier = Tier.C
    width: int = 0
    height: int = 0
    bytes: int = 0
    format: str = ""
    disc_number: int | None = None
    phash: int | None = None  # 64-bit dHash of the image, when known
    blank: bool = False  # near-uniform image (placeholder / "no image")
    type_confidence: float = 1.0  # provider's confidence this is really `art_type`
    attribution: str = ""
    comment: str = ""
    generated: bool = False
    thumb_url: str = ""  # small preview used for hashing and the dialog
    thumb_data: bytes | None = field(default=None, repr=False)
    data: bytes | None = field(default=None, repr=False)  # full image, fetched lazily
    dims_known: bool = False  # True when width/height are reported by the source or measured
    likes: int = 0
    page: int = 0  # booklet page order
    extra: dict = field(default_factory=dict)  # generation provenance etc.
    # filled by the pipeline
    score: float = 0.0
    breakdown: dict[str, float] = field(default_factory=dict)
    rejected_reason: str | None = None

    @property
    def aspect(self) -> float:
        return (self.width / self.height) if self.height else 0.0

    @property
    def megapixels(self) -> float:
        return (self.width * self.height) / 1_000_000.0
